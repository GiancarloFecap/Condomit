CREATE OR REPLACE FUNCTION public.condomit_has_permission(target_cep TEXT, permission_name TEXT)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT CASE
    WHEN public.condomit_can_manage_cep(target_cep) THEN TRUE
    ELSE COALESCE((
      SELECT rp.enabled
      FROM public.role_permissions rp
      WHERE public.condomit_same_cep(rp.cep, target_cep)
        AND LOWER(rp.role) = public.condomit_current_user_type()
        AND rp.permission = permission_name
      LIMIT 1
    ), FALSE)
  END;
$$;

