CREATE OR REPLACE FUNCTION public.condomit_suggest_lost_found_matches()
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE changed INTEGER := 0; r RECORD; score INTEGER;
BEGIN
  FOR r IN
    SELECT l.id lost_id, f.id found_id, l.cep,
           l.item_name lost_name, f.item_name found_name,
           l.location lost_location, f.location found_location,
           LOWER(COALESCE(l.created_by,'')) lost_creator,
           LOWER(COALESCE(f.created_by,'')) found_creator
    FROM public.lost_and_found_items l
    JOIN public.lost_and_found_items f ON public.condomit_same_cep(l.cep, f.cep) AND l.id <> f.id
    WHERE l.item_type='Perdido' AND f.item_type='Encontrado'
      AND l.item_status='ativo' AND f.item_status='ativo'
      AND public.condomit_can_access_cep(l.cep)
      AND ABS(l.item_date - f.item_date) <= 30
  LOOP
    score := 35;
    IF LOWER(r.lost_name) = LOWER(r.found_name) THEN score := score + 45;
    ELSIF LOWER(r.lost_name) LIKE '%' || LOWER(r.found_name) || '%' OR LOWER(r.found_name) LIKE '%' || LOWER(r.lost_name) || '%' THEN score := score + 30;
    END IF;
    IF LOWER(r.lost_location) = LOWER(r.found_location) THEN score := score + 20; END IF;
    IF score >= 55 THEN
      INSERT INTO public.lost_found_matches(cep,lost_item_id,found_item_id,confidence,status)
      VALUES(r.cep,r.lost_id,r.found_id,LEAST(score,100),'sugerido')
      ON CONFLICT(lost_item_id,found_item_id) DO UPDATE SET confidence=EXCLUDED.confidence;

      IF COALESCE(r.lost_creator,'') <> '' THEN
        INSERT INTO public.notifications(
          cep,category,title,description,recipient_email,event_type,event_key,created_at
        ) VALUES (
          r.cep,'Avisos','Possível item encontrado',
          'Encontramos uma possível correspondência para "' || r.lost_name || '". Abra Achados e Perdidos para conferir.',
          r.lost_creator,'lost_found_match',
          'lost_found_match:' || r.lost_id::TEXT || ':' || r.found_id::TEXT || ':' || r.lost_creator,
          NOW()
        ) ON CONFLICT (event_key) DO NOTHING;
      END IF;

      IF COALESCE(r.found_creator,'') <> '' AND r.found_creator <> r.lost_creator THEN
        INSERT INTO public.notifications(
          cep,category,title,description,recipient_email,event_type,event_key,created_at
        ) VALUES (
