CREATE OR REPLACE FUNCTION public.condomit_notify_old_packages()
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE p RECORD; notified INTEGER := 0;
BEGIN
  IF public.condomit_current_user_type() NOT IN ('porteiro','sindico','síndico','admin','administradora') THEN
    RAISE EXCEPTION 'Sem permissão.' USING ERRCODE='42501';
  END IF;
  FOR p IN
    SELECT * FROM public.packages
    WHERE public.condomit_can_access_cep(cep)
      AND status = 'Aguardando retirada'
      AND received_at <= NOW() - INTERVAL '3 days'
      AND overdue_notified_at IS NULL
  LOOP
    INSERT INTO public.notifications(cep,category,title,description,recipient_email,event_type,event_key,created_at)
    VALUES(p.cep,'Entregas','Encomenda aguardando retirada',
      'Sua encomenda está na portaria há mais de 3 dias. Código de retirada: ' || COALESCE(p.pickup_code,'--'),
      LOWER(p.recipient_email),'package_overdue','package_overdue:'||p.id::TEXT,NOW())
    ON CONFLICT (event_key) DO NOTHING;
    UPDATE public.packages SET overdue_notified_at = NOW() WHERE id = p.id;
    notified := notified + 1;
  END LOOP;
  RETURN notified;
END;
$$;

