CREATE OR REPLACE FUNCTION public.condomit_expire_marketplace_items()
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE changed INTEGER;
BEGIN
  UPDATE public.marketplace_items
     SET item_status = 'expirado'
   WHERE item_status IN ('disponivel','reservado')
     AND expires_at IS NOT NULL
     AND expires_at < NOW()
     AND public.condomit_can_access_cep(cep);
  GET DIAGNOSTICS changed = ROW_COUNT;
  RETURN changed;
END;
$$;

