-- Auditoria automática dos módulos críticos.
CREATE OR REPLACE FUNCTION public.condomit_audit_row_change()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE data JSONB; target_cep TEXT; target_id TEXT;
BEGIN
  data := CASE WHEN TG_OP = 'DELETE' THEN TO_JSONB(OLD) ELSE TO_JSONB(NEW) END;
  target_cep := COALESCE(data->>'cep', data->>'condominium_cep');
  target_id := COALESCE(data->>'id', data->>'email', '');
  IF COALESCE(target_cep,'') <> '' AND public.condomit_auth_email() <> '' THEN
    INSERT INTO public.audit_log(cep,actor_email,action,entity_type,entity_id,details)
    VALUES(target_cep,public.condomit_auth_email(),LOWER(TG_OP),TG_TABLE_NAME,target_id,JSONB_BUILD_OBJECT('operation',TG_OP));
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

