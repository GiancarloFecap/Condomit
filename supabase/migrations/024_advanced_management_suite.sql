CREATE OR REPLACE FUNCTION public.condomit_generate_due_maintenance()
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  item RECORD;
  inserted_count INTEGER := 0;
BEGIN
  FOR item IN
    SELECT * FROM public.maintenance_templates mt
    WHERE mt.active = TRUE
      AND mt.next_due <= CURRENT_DATE
      AND public.condomit_can_manage_cep(mt.cep)
  LOOP
    INSERT INTO public.maintenance_items(
      cep, title, description, location, category, frequency, next_date,
      status, created_by, asset_id, template_id
    ) VALUES (
      item.cep, item.title, item.description, item.location, item.category,
      item.interval_days::TEXT || ' dias', item.next_due, 'pendente',
      public.condomit_auth_email(), item.asset_id, item.id
    );

    UPDATE public.maintenance_templates
       SET next_due = item.next_due + item.interval_days,
           updated_at = NOW()
     WHERE id = item.id;
    inserted_count := inserted_count + 1;
  END LOOP;
  RETURN inserted_count;
END;
$$;

