-- 0.2 VISITORS
-- Garante que a coluna CEP exista
-- ============================================================

ALTER TABLE IF EXISTS public.visitors
ADD COLUMN IF NOT EXISTS cep TEXT;


-- Garante FK do CEP de visitors
DO $$
BEGIN

    IF EXISTS (
        SELECT 1
        FROM information_schema.tables
        WHERE table_schema = 'public'
        AND table_name = 'visitors'
    )
    AND NOT EXISTS (
        SELECT 1
        FROM information_schema.table_constraints
        WHERE constraint_schema = 'public'
        AND constraint_name = 'visitors_cep_fkey'
    )
    THEN

        BEGIN

            ALTER TABLE public.visitors
            ADD CONSTRAINT visitors_cep_fkey
            FOREIGN KEY (cep)
            REFERENCES public.condominiums (cep)
            ON UPDATE CASCADE
            ON DELETE SET NULL;

        EXCEPTION
            WHEN duplicate_object THEN
                NULL;

            WHEN OTHERS THEN
                RAISE NOTICE
                'Não foi possível criar visitors_cep_fkey: %',
                SQLERRM;
        END;

    END IF;

END
$$;


