assembly_chat_messages_insert_policy
ON public.assembly_chat_messages
FOR INSERT
TO authenticated
WITH CHECK (

    -- Precisa ter usuário autenticado
    public.condomit_auth_email() <> ''

    AND

    -- O usuário só pode enviar mensagem
    -- utilizando o próprio e-mail
    LOWER(
        COALESCE(
            assembly_chat_messages.user_email,
            ''
        )
    )
    =
    public.condomit_auth_email()

    AND

    -- Precisa pertencer ao condomínio
    public.condomit_user_belongs_to_cep(
        assembly_chat_messages.cep
    )

    AND

    -- Assembleia precisa existir
    AND EXISTS (

        SELECT 1

        FROM public.scheduled_assemblies sa

        WHERE

            sa.id =
                assembly_chat_messages.assembly_id

            AND

            public.condomit_same_cep(
                sa.cep,
                assembly_chat_messages.cep
            )

            AND

            sa.status IN (
                'agendada',
                'em_andamento'
            )

    )

);


