-- ------------------------------------------------------------
-- 1.1 E-mail do usuário autenticado
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.condomit_auth_email()
RETURNS TEXT
LANGUAGE sql
STABLE
AS $$
    SELECT LOWER(
        COALESCE(
            auth.jwt() ->> 'email',
            ''
        )
    );
$$;


-- ------------------------------------------------------------
-- 1.2 Comparar CEP
--
-- Permite comparar:
-- 04284-070
-- com
-- 04284070
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.condomit_same_cep(
    a TEXT,
    b TEXT
)
RETURNS BOOLEAN
LANGUAGE sql
IMMUTABLE
AS $$

    SELECT

        NULLIF(
            REGEXP_REPLACE(
                COALESCE(a, ''),
                '\D',
                '',
                'g'
            ),
            ''
        ) IS NOT NULL

        AND

        REGEXP_REPLACE(
            COALESCE(a, ''),
            '\D',
            '',
            'g'
        )

        =

        REGEXP_REPLACE(
            COALESCE(b, ''),
            '\D',
            '',
            'g'
        );

$$;


-- ------------------------------------------------------------
-- 1.3 Verificar se usuário pertence ao condomínio
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION
public.condomit_user_belongs_to_cep(
    target_cep TEXT
)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$

    SELECT

        public.condomit_auth_email() <> ''

        AND

        (

            -- ----------------------------------------------
            -- Tenta primeiro user_condominiums
            -- ----------------------------------------------

            EXISTS (

                SELECT 1

                FROM public.user_condominiums uc

                WHERE

                    LOWER(
                        COALESCE(
                            uc.user_email,
                            ''
                        )
                    )
                    =
                    public.condomit_auth_email()

                    AND

                    public.condomit_same_cep(
                        uc.condominium_id,
                        target_cep
                    )

            )


            OR


            -- ----------------------------------------------
            -- Fallback:
            -- campo condominium JSONB da tabela users
            -- ----------------------------------------------

            EXISTS (

                SELECT 1

                FROM public.users u

                WHERE

                    LOWER(
                        COALESCE(
                            u.email,
                            ''
                        )
                    )
                    =
                    public.condomit_auth_email()

                    AND

                    jsonb_typeof(
                        u.condominium
                    ) = 'object'

                    AND (

                        public.condomit_same_cep(
                            u.condominium ->> 'cep',
                            target_cep
                        )

                        OR

                        public.condomit_same_cep(
                            u.condominium ->> 'condominium_id',
                            target_cep
                        )

                    )

            )

        );

$$;


-- ------------------------------------------------------------
-- 1.4 Tipo do usuário autenticado
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION
public.condomit_current_user_type()
RETURNS TEXT
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$

    SELECT LOWER(
        COALESCE(
            (
                SELECT u.user_type

                FROM public.users u

                WHERE
                    LOWER(
                        COALESCE(
                            u.email,
                            ''
                        )
                    )
                    =
                    public.condomit_auth_email()

                LIMIT 1
            ),
            ''
        )
    );

$$;


-- ------------------------------------------------------------
-- 1.5 CPF do usuário autenticado
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION
public.condomit_current_user_cpf()
RETURNS TEXT
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$

    SELECT REGEXP_REPLACE(

        COALESCE(
            (
                SELECT u.cpf

                FROM public.users u

                WHERE
                    LOWER(
                        COALESCE(
                            u.email,
                            ''
                        )
                    )
                    =
                    public.condomit_auth_email()

                LIMIT 1
            ),
            ''
        ),

        '\D',
        '',
        'g'

    );

$$;


